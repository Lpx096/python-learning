#使用str（）将制定数据转换为字符串
result1 = str(18)
result2 = str(23.4)
print(type(result1),result1)
print(type(result2),result2)
#使用int（）将制定数据转换为整型
#错误 （‘15.4’） （ 4 4 ） （‘出货’） （‘87个’）
result3 = float(18)
print(type(result3),result3)
result4 = float( 23 )
print(type(result4),result4)
result5 = int( 23 )
print(type(result5),result5)
result6 = int(56.3)
print(type(result6),result6)
result7 = str('99')
print(type(result7),result7)