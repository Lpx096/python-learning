#age += 1 等价于 age = age + 1（加法赋值运算符）
age = 18
age += 1
print(age)

price = 52
freight = 6
price += freight
print(price)
#减法复合运算符
age -= 1
print(age)
#乘法复合运算符
a = 2
a *= 3
print(a)
#除法复合运算符
a = 4
a /= 2
print(a)
#取整复合运算符
a = 7
a //= 2
print(a)

#取模赋值运算符
a = 386
a %= 60
print(a)

#指数赋值运算符
a = 2
a **= 3
print(a)